#!/usr/bin/env node
/**
 * Deterministic Soroban contract reference generator.
 *
 * Reads the WASM-derived `packages/bindings/<contract>/interface.json`
 * (decoded from each contract's `contractspecv0` custom section) and merges
 * curated non-spec annotations from `docs/reference/<contract>.annotations.toml`
 * to emit `docs/reference/<contract>.md`.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
export const REPO_STELLAR_ROOT = resolve(__dirname, "../..");
export const CONTRACTS = ["market-core", "resolver", "treasury", "reasoning-registry"];

/**
 * Minimal deterministic TOML parser supporting `[section.key]` tables with
 * double-quoted string values (`key = "value"`), comments (`#`), and blank lines.
 */
export function parseAnnotationsToml(tomlText) {
  const result = { functions: {}, storage: {} };
  let currentGroup = null;
  let currentKey = null;

  for (const rawLine of tomlText.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;

    const sectionMatch = /^\[([a-zA-Z0-9_-]+)\.([a-zA-Z0-9_:-]+)\]$/.exec(line);
    if (sectionMatch) {
      const [, group, key] = sectionMatch;
      if (group !== "functions" && group !== "storage") {
        throw new Error(`Unsupported annotation section [${group}.${key}]`);
      }
      currentGroup = group;
      currentKey = key;
      if (!result[group][key]) result[group][key] = {};
      continue;
    }

    const kvMatch = /^([a-zA-Z0-9_]+)\s*=\s*"((?:\\.|[^"\\])*)"\s*(?:#.*)?$/.exec(line);
    if (kvMatch && currentGroup && currentKey) {
      const [, field, rawVal] = kvMatch;
      const value = rawVal.replace(/\\"/g, '"').replace(/\\n/g, "\n").replace(/\\\\/g, "\\");
      result[currentGroup][currentKey][field] = value;
      continue;
    }

    throw new Error(`Invalid TOML annotation line: ${rawLine}`);
  }

  return result;
}

export function escapeTableCell(text) {
  if (!text) return "—";
  return String(text)
    .replace(/\r?\n+/g, " ")
    .replace(/\|/g, "\\|")
    .trim() || "—";
}

export function formatType(typeSpec) {
  if (typeof typeSpec === "string") {
    const primitives = {
      val: "Val",
      bool: "bool",
      void: "()",
      error: "Error",
      u32: "u32",
      i32: "i32",
      u64: "u64",
      i64: "i64",
      timepoint: "Timepoint",
      duration: "Duration",
      u128: "u128",
      i128: "i128",
      u256: "u256",
      i256: "i256",
      bytes: "Bytes",
      string: "String",
      symbol: "Symbol",
      address: "Address",
      muxed_address: "MuxedAddress",
    };
    return primitives[typeSpec] ?? typeSpec;
  }
  if (!typeSpec || typeof typeSpec !== "object") return "unknown";
  if ("udt" in typeSpec) {
    return typeof typeSpec.udt === "string" ? typeSpec.udt : typeSpec.udt.name;
  }
  if ("option" in typeSpec) {
    const inner = typeSpec.option.value_type ?? typeSpec.option;
    return `Option<${formatType(inner)}>`;
  }
  if ("result" in typeSpec) {
    return `Result<${formatType(typeSpec.result.ok_type)}, ${formatType(typeSpec.result.error_type)}>`;
  }
  if ("vec" in typeSpec) {
    const inner = typeSpec.vec.element_type ?? typeSpec.vec;
    return `Vec<${formatType(inner)}>`;
  }
  if ("map" in typeSpec) {
    return `Map<${formatType(typeSpec.map.key_type)}, ${formatType(typeSpec.map.value_type)}>`;
  }
  if ("tuple" in typeSpec) {
    const items = typeSpec.tuple.value_types ?? typeSpec.tuple;
    return `(${items.map(formatType).join(", ")})`;
  }
  if ("bytes_n" in typeSpec) {
    const n = typeSpec.bytes_n.n ?? typeSpec.bytes_n;
    return `BytesN<${n}>`;
  }
  return JSON.stringify(typeSpec);
}

export function renderContractDoc(contractName, manifest, annotations) {
  const fnNames = Object.keys(manifest.functions ?? {}).sort();
  const annotatedFns = annotations.functions ?? {};

  // Validate annotations against exported spec functions
  for (const name of Object.keys(annotatedFns).sort()) {
    if (!(name in (manifest.functions ?? {}))) {
      throw new Error(
        `[${contractName}] Annotation references unknown function "${name}" (not present in contract spec)`
      );
    }
  }
  for (const name of fnNames) {
    const ann = annotatedFns[name];
    if (!ann || !ann.caller || !ann.caller.trim()) {
      throw new Error(
        `[${contractName}] Missing required "caller" annotation for function "${name}"`
      );
    }
  }

  const lines = [];
  lines.push(`<!-- Generated by scripts/gen-contract-docs/generate.mjs — DO NOT EDIT BY HAND -->`);
  lines.push(`# \`${contractName}\` Contract Reference`);
  lines.push("");
  lines.push(
    `Generated deterministically from \`packages/bindings/${contractName}/interface.json\` (decoded from the compiled WASM \`contractspecv0\` section) and \`docs/reference/${contractName}.annotations.toml\`.`
  );
  lines.push("");

  // --- Functions ---
  lines.push("## Functions");
  lines.push("");
  lines.push("| Function | Caller / Auth | Returns | Summary |");
  lines.push("| --- | --- | --- | --- |");
  for (const name of fnNames) {
    const fnSpec = manifest.functions[name].spec;
    const ann = annotatedFns[name];
    const outputs = fnSpec.outputs ?? [];
    const ret = outputs.length === 0 ? "()" : outputs.map(formatType).join(", ");
    const summary = fnSpec.doc || ann.notes || "";
    lines.push(
      `| [\`${name}\`](#fn-${name.replace(/_/g, "-")}) | ${escapeTableCell(ann.caller)} | \`${escapeTableCell(ret)}\` | ${escapeTableCell(summary)} |`
    );
  }
  lines.push("");

  for (const name of fnNames) {
    const fnSpec = manifest.functions[name].spec;
    const ann = annotatedFns[name];
    const args = (fnSpec.inputs ?? []).map((inp) => `${inp.name}: ${formatType(inp.type_)}`).join(", ");
    const outputs = fnSpec.outputs ?? [];
    const ret = outputs.length === 0 ? "" : ` -> ${outputs.map(formatType).join(", ")}`;

    lines.push(`<a id="fn-${name.replace(/_/g, "-")}"></a>`);
    lines.push(`### \`${name}\``);
    lines.push("");
    lines.push("```rust");
    lines.push(`fn ${name}(${args})${ret}`);
    lines.push("```");
    lines.push("");
    lines.push(`- **Caller / Auth:** ${ann.caller}`);
    if (fnSpec.doc) {
      lines.push(`- **Spec Doc:** ${fnSpec.doc.replace(/\r?\n+/g, " ").trim()}`);
    }
    if (ann.notes) {
      lines.push(`- **Notes:** ${ann.notes}`);
    }
    lines.push("");
  }

  // --- Types ---
  const typeOrigins = manifest.type_origins ?? {};
  const allTypes = manifest.types ?? {};
  const typeNames = Object.keys(allTypes)
    .filter((t) => t !== "DataKey")
    .sort();

  lines.push("## Types");
  lines.push("");
  if (typeNames.length === 0) {
    lines.push("_No custom non-storage types exported._");
    lines.push("");
  } else {
    for (const typeName of typeNames) {
      const entry = allTypes[typeName];
      const origin = typeOrigins[typeName];
      lines.push(`### \`${typeName}\``);
      lines.push("");
      if (origin && origin !== contractName) {
        lines.push(
          `> Imported from [\`${origin}\`](./${origin}.md#${typeName.toLowerCase()}) via \`contractimport!\`.`
        );
        lines.push("");
        continue;
      }
      if (entry.spec?.doc) {
        lines.push(entry.spec.doc.trim());
        lines.push("");
      }
      if (entry.kind === "udt_struct_v0") {
        lines.push("| Field | Type | Description |");
        lines.push("| --- | --- | --- |");
        for (const f of entry.spec.fields ?? []) {
          lines.push(
            `| \`${f.name}\` | \`${escapeTableCell(formatType(f.type_))}\` | ${escapeTableCell(f.doc)} |`
          );
        }
        lines.push("");
      } else if (entry.kind === "udt_union_v0") {
        lines.push("| Variant | Payload | Description |");
        lines.push("| --- | --- | --- |");
        for (const c of entry.spec.cases ?? []) {
          if (c.void_v0) {
            lines.push(`| \`${c.void_v0.name}\` | — | ${escapeTableCell(c.void_v0.doc)} |`);
          } else if (c.tuple_v0) {
            const payload = (c.tuple_v0.type_ ?? []).map(formatType).join(", ");
            lines.push(
              `| \`${c.tuple_v0.name}\` | \`(${escapeTableCell(payload)})\` | ${escapeTableCell(c.tuple_v0.doc)} |`
            );
          }
        }
        lines.push("");
      } else if (entry.kind === "udt_enum_v0") {
        lines.push("| Variant | Value | Description |");
        lines.push("| --- | --- | --- |");
        for (const c of entry.spec.cases ?? []) {
          lines.push(`| \`${c.name}\` | \`${c.value}\` | ${escapeTableCell(c.doc)} |`);
        }
        lines.push("");
      }
    }
  }

  // --- Errors ---
  lines.push("## Errors");
  lines.push("");
  const errorGroups = Object.keys(manifest.errors ?? {}).sort();
  if (errorGroups.length === 0) {
    lines.push("_No error enums exported._");
    lines.push("");
  } else {
    for (const errName of errorGroups) {
      const errCases = [...(manifest.errors[errName].spec?.cases ?? [])].sort(
        (a, b) => Number(a.value) - Number(b.value)
      );
      lines.push(`### \`${errName}\``);
      lines.push("");
      lines.push("| Code | Name | Description |");
      lines.push("| --- | --- | --- |");
      for (const c of errCases) {
        lines.push(`| ${c.value} | \`${c.name}\` | ${escapeTableCell(c.doc)} |`);
      }
      lines.push("");
    }
  }

  // --- Events ---
  lines.push("## Events");
  lines.push("");
  const eventNames = Object.keys(manifest.events ?? {}).sort();
  if (eventNames.length === 0) {
    lines.push("_No events exported._");
    lines.push("");
  } else {
    for (const evName of eventNames) {
      const ev = manifest.events[evName].spec;
      const prefixTopics = ev.prefix_topics ?? [];
      const topicParams = (ev.params ?? []).filter((p) => p.location === "topic_list");
      const dataParams = (ev.params ?? []).filter((p) => p.location !== "topic_list");

      lines.push(`### \`${evName}\``);
      lines.push("");
      if (ev.doc) {
        lines.push(ev.doc.trim());
        lines.push("");
      }
      lines.push(
        `- **Prefix topics:** ${prefixTopics.length > 0 ? prefixTopics.map((t) => `\`"${t}"\``).join(", ") : "—"}`
      );
      lines.push(
        `- **Topic fields:** ${
          topicParams.length > 0
            ? topicParams.map((p) => `\`${p.name}: ${formatType(p.type_)}\``).join(", ")
            : "—"
        }`
      );
      lines.push(
        `- **Data fields (\`${ev.data_format ?? "map"}\`):** ${
          dataParams.length > 0
            ? dataParams.map((p) => `\`${p.name}: ${formatType(p.type_)}\``).join(", ")
            : "—"
        }`
      );
      const filterTopics = [
        ...prefixTopics.map((t) => `Symbol("${t}")`),
        ...topicParams.map(() => `"*"`),
      ];
      lines.push(`- **Indexer filter:** \`[${filterTopics.join(", ")}]\``);
      lines.push("");
    }
  }

  // --- Storage Keys ---
  lines.push("## Storage Keys");
  lines.push("");
  const dataKey = allTypes["DataKey"];
  const storageAnns = annotations.storage ?? {};
  const storageKeys = new Map();

  if (dataKey?.kind === "udt_union_v0") {
    for (const c of dataKey.spec.cases ?? []) {
      const info = c.void_v0 ?? c.tuple_v0;
      if (!info) continue;
      const payload = c.tuple_v0 ? `(${(c.tuple_v0.type_ ?? []).map(formatType).join(", ")})` : "—";
      storageKeys.set(info.name, { payload, doc: info.doc ?? "" });
    }
  }
  for (const key of Object.keys(storageAnns).sort()) {
    if (!storageKeys.has(key)) {
      storageKeys.set(key, { payload: "—", doc: "" });
    }
  }

  if (storageKeys.size === 0) {
    lines.push("_Storage key enum is internal to the contract crate._");
    lines.push("");
  } else {
    lines.push("| Key | Payload | Durability | TTL / Notes |");
    lines.push("| --- | --- | --- | --- |");
    for (const key of [...storageKeys.keys()].sort()) {
      const meta = storageKeys.get(key);
      const ann = storageAnns[key] ?? {};
      const notes = [ann.ttl, ann.notes, meta.doc].filter(Boolean).join("; ");
      lines.push(
        `| \`${key}\` | \`${escapeTableCell(meta.payload)}\` | ${escapeTableCell(ann.durability)} | ${escapeTableCell(notes)} |`
      );
    }
    lines.push("");
  }

  return `${lines.join("\n")}\n`;
}

export function generateAll({ rootDir = REPO_STELLAR_ROOT, contracts = CONTRACTS } = {}) {
  const outDir = resolve(rootDir, "docs/reference");
  mkdirSync(outDir, { recursive: true });
  const generated = {};

  for (const name of contracts) {
    const manifestPath = resolve(rootDir, "packages/bindings", name, "interface.json");
    const annPath = resolve(outDir, `${name}.annotations.toml`);
    if (!existsSync(manifestPath)) {
      throw new Error(`Missing interface manifest: ${manifestPath}`);
    }
    if (!existsSync(annPath)) {
      throw new Error(`Missing annotations sidecar: ${annPath}`);
    }
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    const annotations = parseAnnotationsToml(readFileSync(annPath, "utf8"));
    const markdown = renderContractDoc(name, manifest, annotations);
    const outPath = resolve(outDir, `${name}.md`);
    writeFileSync(outPath, markdown, "utf8");
    generated[name] = outPath;
  }

  return generated;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const generated = generateAll();
  for (const [name, outPath] of Object.entries(generated)) {
    console.log(`Generated ${name} -> ${outPath}`);
  }
}
