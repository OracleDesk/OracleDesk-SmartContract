//! This crate ships no contract. Its tests drive several contracts together:
//! see `tests/treasury_caps_exhaustive/`.

pub mod world;

#[allow(clippy::too_many_arguments)]
pub mod market_core {
    soroban_sdk::contractimport!(file = "wasm/market_core.wasm");
}

#[allow(clippy::too_many_arguments)]
pub mod resolver {
    soroban_sdk::contractimport!(file = "wasm/resolver.wasm");
}

pub mod treasury {
    soroban_sdk::contractimport!(file = "wasm/treasury.wasm");
}

#[allow(clippy::too_many_arguments)]
pub mod reasoning_registry {
    soroban_sdk::contractimport!(file = "wasm/reasoning_registry.wasm");
}

// Router and timelock are registered from their native contract types in
// `World` (no vendored router.wasm exists in this crate yet). Re-exporting
// them under the same names keeps the test-side clients uniform. `::router`
// and `::timelock` below refer to the external crates, not these modules.
pub mod router {
    pub use ::router::*;

    /// Match the name generated by `contractimport!` for the wasm-backed
    /// modules so `World` keeps one client shape for all six contracts.
    pub type Client<'a> = RouterClient<'a>;
}

pub mod timelock {
    pub use ::timelock::*;

    /// See the `router` module above.
    pub type Client<'a> = TimelockClient<'a>;
}
